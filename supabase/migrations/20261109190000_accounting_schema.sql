-- Recreates the imported Flutter tables, security-invoker views, and row level security.

create schema if not exists private;

create table if not exists public.business (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  reference uuid default gen_random_uuid(),
  business_name text,
  buiness_phone text,
  business_email text,
  "business_GST" text,
  "business_State" text,
  "business_StateCode" text,
  business_mobile text,
  business_address text,
  business_bank jsonb,
  business_owner text,
  business_upi text,
  table_number jsonb,
  business_logo text
);


create table if not exists public."Roles" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
