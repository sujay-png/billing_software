with (security_invoker = true) as
select
  c.id as customer_id,
  c.reference as customer_ref,
  e.id as estimate_id,
  e.estimate_grandtotalroundoff,
  c.customer_name,
  c.customer_phone,
  c.customer_email,
  c."customer_GST",
  c.customer_businessname,
  e.estimate_no,
  e.customer_custombilling,
  e."customer_customDelivery",
  e.estimate_date,
  e.estimate_items,
  e.estimate_discount,
  e.estimate_subtotal,
  e.estimate_tax,
  e."estimate_grantTotal",
  e."estimate_paymentTerms" as payment_terms,
