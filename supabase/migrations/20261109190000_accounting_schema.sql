create or replace function private.my_business_ids()
returns setof bigint
language sql
stable
security definer
set search_path = public
as $$
  select business_ref
  from public."Useraccount"
  where auth_user_id = auth.uid()
    and business_ref is not null
$$;

revoke all on function private.my_business_ids() from public;
grant usage on schema private to authenticated;
grant execute on function private.my_business_ids() to authenticated;

alter table public.business enable row level security;
alter table public."Roles" enable row level security;
alter table public."Useraccount" enable row level security;
alter table public."Customers" enable row level security;
alter table public."Items" enable row level security;
alter table public."Estimates" enable row level security;
alter table public."Invoices" enable row level security;

create policy business_select on public.business
  for select to authenticated
  using (id in (select private.my_business_ids()));
create policy business_update on public.business
  for update to authenticated
  using (id in (select private.my_business_ids()))
  with check (id in (select private.my_business_ids()));

create policy roles_select on public."Roles"
  for select to authenticated
  using (true);

create policy useraccount_select on public."Useraccount"
  for select to authenticated
  using (auth_user_id = auth.uid());
create policy useraccount_update on public."Useraccount"
  for update to authenticated
  using (auth_user_id = auth.uid())
  with check (auth_user_id = auth.uid());

create policy customers_all on public."Customers"
  for all to authenticated
  using (business_ref in (select private.my_business_ids()))
  with check (business_ref in (select private.my_business_ids()));

