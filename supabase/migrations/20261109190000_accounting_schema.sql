  id uuid primary key,
  created_at timestamptz not null default now(),
  reference uuid default gen_random_uuid(),
  user_name text,
  user_email text,
  user_phone text,
  business_ref bigint references public.business(id) on delete set null,
  role bigint references public."Roles"(id) on delete set null,
  auth_user_id uuid unique references auth.users(id) on delete set null
