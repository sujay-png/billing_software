-- Create separate Quotations table
create table if not exists public."Quotations" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  reference uuid default gen_random_uuid(),
  quotation_no text,
  customer_ref bigint references public."Customers"(id) on delete restrict,
  customer_custombilling text,
  "customer_customDelivery" text,
  quotation_date timestamptz,
  "quotation_validDate" timestamptz,
  "quotation_paymentTerms" text,
  quotation_items jsonb not null default '[]'::jsonb,
  quotation_discount numeric not null default 0,
  quotation_subtotal numeric not null default 0,
  quotation_tax numeric not null default 0,
  "quotation_grantTotal" numeric not null default 0,
  quotation_notes text,
  "isDraft" boolean not null default true,
  business_ref bigint references public.business(id) on delete cascade,
  quotation_grandtotalroundoff numeric,
  "isArchive" boolean not null default false,
  refnumber text
);

-- Index for performant querying
create index if not exists quotations_business_date_idx on public."Quotations" (business_ref, quotation_date desc);

-- Enable Row Level Security (RLS)
alter table public."Quotations" enable row level security;

-- Policy: authenticated users can access quotations of their business
create policy quotations_all on public."Quotations"
  for all to authenticated
  using (business_ref in (select private.my_business_ids()))
  with check (business_ref in (select private.my_business_ids()));

-- Grants
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public."Quotations" to authenticated;
grant usage, select on all sequences in schema public to authenticated;
